-- TRUY VAN SINH VIEN VA LOP
SELECT SV.MaSV, SV.HoTen, L.TenLop
FROM SINHVIEN SV
JOIN LOP L ON SV.MaLop = L.MaLop;

-- TRUY VAN DIEM SINH VIEN
SELECT SV.MaSV, SV.HoTen, MH.TenMH,
D.LanThi, D.DiemTongKet
FROM DIEM D
JOIN SINHVIEN SV ON D.MaSV = SV.MaSV
JOIN MONHOC MH ON D.MaMH = MH.MaMH;

-- TINH DIEM TRUNG BINH
SELECT SV.MaSV, SV.HoTen,
ROUND(AVG(D.DiemTongKet),2) AS DiemTrungBinh
FROM SINHVIEN SV
JOIN DIEM D ON SV.MaSV = D.MaSV
GROUP BY SV.MaSV, SV.HoTen;

-- THONG KE SINH VIEN THEO LOP
SELECT L.MaLop, L.TenLop,
COUNT(SV.MaSV) AS SoLuongSinhVien
FROM LOP L
LEFT JOIN SINHVIEN SV ON L.MaLop = SV.MaLop
GROUP BY L.MaLop, L.TenLop;
