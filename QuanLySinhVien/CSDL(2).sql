CREATE DATABASE IF NOT EXISTS QL_SINHVIEN
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE QL_SINHVIEN;

CREATE TABLE LOP (
    MaLop VARCHAR(10) PRIMARY KEY,
    TenLop VARCHAR(100) NOT NULL,
    KhoaHoc VARCHAR(20) NOT NULL,
    NganhHoc VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE SINHVIEN (
    MaSV VARCHAR(10) PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE NOT NULL,
    GioiTinh ENUM('Nam','Nu','Khac') NOT NULL,
    Email VARCHAR(100) UNIQUE,
    SoDienThoai VARCHAR(15) UNIQUE,
    DiaChi VARCHAR(255),
    MaLop VARCHAR(10) NOT NULL,
    FOREIGN KEY (MaLop) REFERENCES LOP(MaLop)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE MONHOC (
    MaMH VARCHAR(10) PRIMARY KEY,
    TenMH VARCHAR(100) NOT NULL,
    SoTinChi INT NOT NULL,
    HocKy INT NOT NULL,
    MoTa VARCHAR(255),
    CHECK (SoTinChi BETWEEN 1 AND 10),
    CHECK (HocKy BETWEEN 1 AND 3)
) ENGINE=InnoDB;

CREATE TABLE DIEM (
    MaSV VARCHAR(10) NOT NULL,
    MaMH VARCHAR(10) NOT NULL,
    LanThi INT NOT NULL DEFAULT 1,
    DiemQuaTrinh DECIMAL(4,2) NOT NULL,
    DiemThi DECIMAL(4,2) NOT NULL,
    DiemTongKet DECIMAL(4,2) NOT NULL,
    PRIMARY KEY (MaSV, MaMH, LanThi),
    FOREIGN KEY (MaSV) REFERENCES SINHVIEN(MaSV)
    ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (MaMH) REFERENCES MONHOC(MaMH)
    ON UPDATE CASCADE ON DELETE RESTRICT,
    CHECK (LanThi >= 1),
    CHECK (DiemQuaTrinh BETWEEN 0 AND 10),
    CHECK (DiemThi BETWEEN 0 AND 10),
    CHECK (DiemTongKet BETWEEN 0 AND 10)
) ENGINE=InnoDB;

